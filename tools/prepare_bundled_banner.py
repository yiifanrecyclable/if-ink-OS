"""中文：将已定稿PNG无损压缩为内置素材，不修改原图。 / Losslessly pack the approved PNG without editing it."""
from pathlib import Path
import hashlib,struct,zlib
ROOT=Path(__file__).resolve().parents[1]
data=(ROOT/'assets/banner/default-banner.png').read_bytes()
assert data[:8]==b'\x89PNG\r\n\x1a\n' and struct.unpack('>II',data[16:24])==(684,300)
packed=zlib.compress(data,9)
text='/* Generated by tools/prepare_bundled_banner.py; do not edit. SPDX-License-Identifier: Apache-2.0 */\n#pragma once\n'
text+=f'#define BUNDLED_BANNER_SIZE {len(data)}u\n#define BUNDLED_BANNER_CRC 0x{zlib.crc32(data):08x}u\n'
text+='static const unsigned char bundled_banner_z[] = {\n'
text+=''.join('    '+','.join(f'0x{x:02x}' for x in packed[i:i+20])+',\n' for i in range(0,len(packed),20))+'};\n'
(ROOT/'main/assets/bundled_banner.h').write_text(text)
print('Packed original PNG:',len(data),'->',len(packed),'bytes; SHA256',hashlib.sha256(data).hexdigest())
