"""中文：将默认壁纸打包为16阶灰度PNG及压缩资源。/ Pack the default wallpaper as a 16-tone PNG and compressed resource."""
from pathlib import Path
import argparse,struct,zlib,hashlib
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--src',type=Path);args=p.parse_args()
image=ROOT/'assets/wallpaper/default-wallpaper.png'
if args.src:
    from PIL import Image
    with Image.open(args.src) as im:
        if im.size!=(684,1216):raise ValueError('Expected 684x1216; never crop the approved wallpaper')
        values=[min(15,(v+8)//17) for v in im.convert('L').getdata()]
    def chunk(kind,data):return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data))
    packed=bytes((values[i]<<4)|values[i+1] for i in range(0,len(values),2))
    rows=b''.join(b'\0'+packed[y*342:(y+1)*342] for y in range(1216))
    image.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',684,1216,4,0,0,0,0))+chunk(b'IDAT',zlib.compress(rows,9))+chunk(b'IEND',b''))
data=image.read_bytes();assert struct.unpack('>II',data[16:24])==(684,1216)
packed=zlib.compress(data,9)
text='/* Generated by tools/prepare_bundled_wallpaper.py; do not edit. SPDX-License-Identifier: Apache-2.0 */\n#pragma once\n'
text+=f'#define BUNDLED_WALLPAPER_SIZE {len(data)}u\n#define BUNDLED_WALLPAPER_CRC 0x{zlib.crc32(data):08x}u\n'
text+='static const unsigned char bundled_wallpaper_z[] = {\n'+''.join('    '+','.join(f'0x{x:02x}' for x in packed[i:i+20])+',\n' for i in range(0,len(packed),20))+'};\n'
(ROOT/'main/assets/bundled_wallpaper.h').write_text(text)
print('Wallpaper PNG',len(data),'compressed',len(packed),'SHA256',hashlib.sha256(data).hexdigest())
