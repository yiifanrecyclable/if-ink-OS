"""Pack the official Nutstore emblem for the Apps grid as a 4bpp bitmap."""

import argparse
from hashlib import sha256
from pathlib import Path

from PIL import Image


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("logo", type=Path, help="Official 198×59 Nutstore logo PNG")
args = parser.parse_args()
source = args.logo.read_bytes()
expected = "2cd86c999bd6a5fe13e48033e2aa792b9f1a1435c5a3d5d690da9cb3bd558796"
if sha256(source).hexdigest() != expected:
    parser.error("Logo does not match the referenced Nutstore artwork")

width, height = 96, 66
background = 0xee
with Image.open(args.logo) as logo:
    emblem = logo.convert("RGBA").crop((1, 2, 81, 57))
emblem = emblem.resize((width, height), Image.Resampling.LANCZOS)
tile = Image.new("RGBA", emblem.size, (background, background, background, 255))
gray = Image.alpha_composite(tile, emblem).convert("L")
levels = [(value + 8) // 17 for value in gray.tobytes()]
packed = bytes(left | (right << 4) for left, right in zip(levels[::2], levels[1::2]))

lines = [
    "/* Generated by tools/prepare_nutstore_app_icon.py.",
    " * Nutstore's emblem belongs to its original rights holder.",
    " * 4bpp grayscale, low nibble first. See tools/icons/if/README.md. */",
    "#pragma once",
    f"#define NUTSTORE_APP_ICON_WIDTH {width}",
    f"#define NUTSTORE_APP_ICON_HEIGHT {height}",
    f"#define NUTSTORE_APP_ICON_BACKGROUND 0x{background:02x}",
    "static const unsigned char nutstore_app_icon[] = {",
]
for start in range(0, len(packed), 16):
    lines.append("    " + ", ".join(f"0x{value:02x}" for value in packed[start:start + 16]) + ",")
lines.append("};")
output = Path(__file__).resolve().parents[1] / "main/assets/nutstore_app_icon.h"
output.write_text("\n".join(lines) + "\n", encoding="utf-8")
